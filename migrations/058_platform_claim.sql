-- Окно саморегистрации владельцев через MAX.
--
-- Заказчику нужно было впустить в кабинет двух человек, чьи идентификаторы в
-- MAX заранее неизвестны: MAX выдаёт их только при первом входе, а спрашивать
-- их у людей и переносить руками — лишний круг. Поэтому: следующие N входов из
-- MAX от незнакомых людей создают владельца агентства сами, после чего окно
-- закрывается навсегда.
--
-- Счётчик отдельной таблицей, а не полем в настройках агентства, ради атомарности:
-- «UPDATE ... WHERE remaining > 0 RETURNING» не даст двум одновременным входам
-- занять одно и то же место. Иначе на гонке можно было бы получить третьего
-- владельца, а «только двое» здесь — требование, а не пожелание.

CREATE TABLE IF NOT EXISTS platform_claim (
    -- Единственная строка: первичный ключ с проверкой не даёт завести вторую.
    id          BOOLEAN     PRIMARY KEY DEFAULT TRUE CHECK (id),
    remaining   INTEGER     NOT NULL CHECK (remaining >= 0),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO platform_claim (id, remaining) VALUES (TRUE, 2)
ON CONFLICT (id) DO NOTHING;
